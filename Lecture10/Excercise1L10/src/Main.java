import java.util.Arrays;
import java.util.IntSummaryStatistics;
import java.util.List;
import java.util.stream.Collectors;

//TIP To <b>Run</b> code, press <shortcut actionId="Run"/> or
// click the <icon src="AllIcons.Actions.Execute"/> icon in the gutter.
void main() {
    List <Integer> integerList = Arrays.asList(2,3,4,5,6);

    List <String> letters = Arrays.asList("a","b","c","d");

    letters = letters.stream().map(String::toUpperCase).toList();

    System.out.println(letters);

    letters.stream().map(letter -> letter.toUpperCase()).forEach(letter-> System.out.print(letter+ " "));
    letters.stream().map(letter -> letter.toUpperCase()).forEach(System.out::println);

    IntSummaryStatistics statistics = integerList.stream().mapToInt(n->n). summaryStatistics();
    System.out.println(statistics.getSum());
    System.out.println(statistics.getAverage());











































































































































































































































}


public static List<Integer> squareList(List<Integer> list){

    return list.stream().map(i -> i*i).collect(Collectors.toList());
}